def predict_student_performance(study_hours, attendance, previous_score, assignment_score, gender):
    """
    Predict student's final marks based on input features
    """
    try:
        # Validation
        if not all(isinstance(x, (int, float)) for x in [study_hours, attendance, previous_score, assignment_score]):
            return "Error: Please enter valid numbers", None

        if not (0 <= attendance <= 100):
            return "Error: Attendance must be between 0-100%", None

        if not (0 <= previous_score <= 100):
            return "Error: Previous score must be between 0-100", None

        if not (0 <= assignment_score <= 100):
            return "Error: Assignment score must be between 0-100", None

        if not (0 <= study_hours <= 24):
            return "Error: Study hours must be between 0-24", None

        # Encode gender
        gender_encoded = 1 if gender == "Male" else 0

        # Prepare input
        input_data = np.array([[study_hours, attendance, previous_score, assignment_score, gender_encoded]])

        # Make prediction
        predicted_marks = model.predict(input_data)[0]
        predicted_marks = max(0, min(100, predicted_marks))  # Clip to 0-100

        # Determine performance category
        if predicted_marks >= 80:
            category = "🌟 EXCELLENT"
            color = "#28a745"
        elif predicted_marks >= 60:
            category = "✅ GOOD"
            color = "#17a2b8"
        elif predicted_marks >= 40:
            category = "⚠️ AVERAGE"
            color = "#ffc107"
        else:
            category = "❌ NEEDS IMPROVEMENT"
            color = "#dc3545"

        # Create visualization
        fig, axes = plt.subplots(1, 2, figsize=(14, 5))

        # Gauge chart (score distribution)
        axes[0].barh(['Your Prediction'], [predicted_marks], color=color, height=0.5)
        axes[0].barh(['Max Score'], [100], color='lightgray', height=0.5, alpha=0.3)
        axes[0].set_xlim(0, 100)
        axes[0].set_xlabel('Marks', fontsize=12)
        axes[0].set_title('Predicted Final Marks', fontweight='bold', fontsize=12)
        axes[0].text(predicted_marks/2, 0, f'{predicted_marks:.1f}',
                    ha='center', va='center', fontsize=16, fontweight='bold', color='white')

        # Input features bar chart
        features = ['Study Hours\n(normalized)', 'Attendance\n(%)', 'Previous\nScore', 'Assignment\nScore']
        values = [
            (study_hours / 12) * 100,  # Normalize to 0-100
            attendance,
            previous_score,
            assignment_score
        ]

        bars = axes[1].bar(features, values, color=['#3498db', '#e74c3c', '#2ecc71', '#f39c12'])
        axes[1].set_ylabel('Score / Percentage', fontsize=12)
        axes[1].set_title('Input Features Analysis', fontweight='bold', fontsize=12)
        axes[1].set_ylim(0, 100)
        axes[1].grid(axis='y', alpha=0.3)

        # Add value labels on bars
        for bar in bars:
            height = bar.get_height()
            axes[1].text(bar.get_x() + bar.get_width()/2., height,
                        f'{height:.1f}', ha='center', va='bottom', fontweight='bold')

        plt.tight_layout()
        plt.savefig('prediction_result.png', dpi=100, bbox_inches='tight')
        plt.close()

        # Prepare detailed report
        report = f"""
        📊 STUDENT PERFORMANCE PREDICTION REPORT
        {'='*50}

        📈 PREDICTED FINAL MARKS: {predicted_marks:.2f}/100
        📌 PERFORMANCE CATEGORY: {category}

        {'='*50}
        📋 INPUT ANALYSIS:
        • Study Hours: {study_hours:.2f} hours/week
        • Attendance: {attendance:.2f}%
        • Previous Score: {previous_score:.2f}/100
        • Assignment Score: {assignment_score:.2f}/100
        • Gender: {gender}

        {'='*50}
        🎯 RECOMMENDATIONS:
        """

        if predicted_marks < 40:
            report += """
        ⚠️ URGENT: Your performance needs immediate improvement!
        • Increase study hours significantly
        • Improve attendance to at least 80%
        • Focus on assignment quality
        • Consider tutoring support
            """
        elif predicted_marks < 60:
            report += """
        ⚠️ Action needed to improve performance:
        • Increase study hours to 6-8 hours/week
        • Maintain attendance above 85%
        • Complete all assignments on time
        • Practice previous year papers
            """
        elif predicted_marks < 80:
            report += """
        ✅ Good performance! Keep it up:
        • Maintain consistent study routine
        • Continue with regular attendance
        • Review and strengthen weak topics
        • Aim for excellence in the final push
            """
        else:
            report += """
        🌟 EXCELLENT! Outstanding performance:
        • Maintain your study discipline
        • Help other students (peer learning)
        • Explore advanced topics in the subject
        • You're on track for top grades!
            """

        report += f"\n{'='*50}\n✅ Prediction generated successfully!\n"

        return report, "prediction_result.png"

    except Exception as e:
        return f"Error: {str(e)}", None

