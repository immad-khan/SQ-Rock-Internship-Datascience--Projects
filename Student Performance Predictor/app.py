def create_student_data():
    """Generate synthetic student performance dataset"""
    np.random.seed(42)
    n_students = 500

    data = {
        'Study_Hours': np.random.uniform(2, 12, n_students),
        'Attendance': np.random.uniform(50, 100, n_students),
        'Previous_Score': np.random.uniform(40, 95, n_students),
        'Assignment_Score': np.random.uniform(30, 100, n_students),
        'Gender': np.random.choice(['Male', 'Female'], n_students)
    }

    df = pd.DataFrame(data)

    # Create target variable with realistic relationship
    df['Final_Marks'] = (
        df['Study_Hours'] * 5 +
        df['Attendance'] * 0.3 +
        df['Previous_Score'] * 0.4 +
        df['Assignment_Score'] * 0.3 +
        np.random.normal(0, 5, n_students)  # Add noise
    )

    df['Final_Marks'] = df['Final_Marks'].clip(0, 100)
    return df

