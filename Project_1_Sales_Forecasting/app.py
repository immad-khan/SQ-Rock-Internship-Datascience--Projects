def predict_future_sales(days_ahead=30):
    """Predict sales for next N days"""
    last_date = daily_sales['Date'].max()
    future_dates = pd.date_range(start=last_date + timedelta(days=1),
                                  periods=days_ahead, freq='D')

    predictions = []
    last_sales = daily_sales['Sales'].values[-1]

    for date in future_dates:
        feature_dict = {
            'Year': date.year,
            'Month': date.month,
            'Day': date.day,
            'DayOfWeek': date.dayofweek,
            'Quarter': date.quarter,
            'WeekOfYear': date.isocalendar()[1],
            'Sales_Lag1': last_sales,
            'Sales_Lag7': daily_sales['Sales'].values[-7] if len(daily_sales) > 7 else last_sales,
            'Sales_Lag30': daily_sales['Sales'].values[-30] if len(daily_sales) > 30 else last_sales,
            'MA7': daily_sales['MA7'].values[-1],
            'MA30': daily_sales['MA30'].values[-1]
        }

        X_future = pd.DataFrame([feature_dict])
        pred = rf_model.predict(X_future)[0]
        predictions.append({'Date': date, 'Predicted_Sales': pred})
        last_sales = pred

    return pd.DataFrame(predictions)

