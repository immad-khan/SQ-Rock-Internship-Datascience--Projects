def forecast_interface(days_to_predict):
    """
    Gradio interface function for sales forecasting
    """
    try:
        # Validate input
        if not isinstance(days_to_predict, (int, float)) or days_to_predict <= 0:
            return "Error: Please enter a positive number of days", None

        days_to_predict = int(days_to_predict)

        if days_to_predict > 365:
            return "Error: Cannot predict more than 365 days ahead", None

        # Generate predictions
        predictions = predict_future_sales(days_ahead=days_to_predict)

        # Create visualization
        plt.figure(figsize=(14, 6))

        # Historical data
        plt.plot(daily_sales['Date'], daily_sales['Sales'],
                label='Historical Sales', linewidth=2, color='blue')

        # Predictions
        plt.plot(predictions['Date'], predictions['Predicted_Sales'],
                label='Forecasted Sales', linewidth=2, color='red',
                linestyle='--', marker='o')

        plt.title(f'Sales Forecast for Next {days_to_predict} Days',
                 fontsize=14, fontweight='bold')
        plt.xlabel('Date', fontsize=12)
        plt.ylabel('Sales Amount ($)', fontsize=12)
        plt.legend(fontsize=11)
        plt.grid(True, alpha=0.3)
        plt.xticks(rotation=45)
        plt.tight_layout()

        # Save plot
        plt.savefig('forecast_plot.png', dpi=100, bbox_inches='tight')
        plt.close()

        # Prepare summary statistics
        summary = f"""
        SALES FORECAST
        {'='*50}
        Period: Next {days_to_predict} days
        Date Range: {predictions['Date'].min().date()} to {predictions['Date'].max().date()}

        PREDICTIONS STATISTICS:
        Average Forecasted Sales: ${predictions['Predicted_Sales'].mean():.2f}
        Max Predicted Sales: ${predictions['Predicted_Sales'].max():.2f}
        Min Predicted Sales: ${predictions['Predicted_Sales'].min():.2f}

        MODEL PERFORMANCE:
        MAE: ${mae:.2f}
        RMSE: ${rmse:.2f}
        R² Score: {r2:.4f}

        Prediction
        """

        return summary, "forecast_plot.png"

    except Exception as e:
        return f"Error: {str(e)}", None

