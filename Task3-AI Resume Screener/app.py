    def extract_experience(self, text):
        """Extract years of experience"""
        # Look for patterns like "5+ years", "5 years experience"
        patterns = [
            r'(\d+)\+?\s+years?\s+(?:of\s+)?(?:experience|exp)',
            r'(?:experience|exp).*?(\d+)\+?\s+years?',
            r'(\d+)\s+years?\s+in',
        ]

        experiences = []
        for pattern in patterns:
            matches = re.finditer(pattern, text, re.IGNORECASE)
            for match in matches:
                try:
                    years = int(match.group(1))
                    if 0 <= years <= 60:
                        experiences.append(years)
                except:
                    pass

        return max(experiences) if experiences else 0

    def calculate_similarity(self, resume_text, job_desc):
        """Calculate similarity between resume and job description"""
        try:
            resume_cleaned = self.clean_text(resume_text)
            job_cleaned = self.clean_text(job_desc)

            if len(resume_cleaned) < 10 or len(job_cleaned) < 10:
                return 0

            documents = [resume_cleaned, job_cleaned]
            tfidf_matrix = self.vectorizer.fit_transform(documents)
            similarity = cosine_similarity(tfidf_matrix[0:1], tfidf_matrix[1:2])[0][0]
            return similarity * 100
        except Exception as e:
            print(f"Similarity calculation error: {e}")
            return 0

    def screen_resume(self, resume_text, job_desc):
        """Complete resume screening"""
        if not resume_text or len(resume_text) < 20:
            return None

        similarity_score = self.calculate_similarity(resume_text, job_desc)
        skills = self.extract_skills(resume_text)
        experience = self.extract_experience(resume_text)
        job_skills = self.extract_skills(job_desc)

        # Calculate skill match percentage
        matched_skills = [s for s in skills if s in job_skills]
        skill_match_pct = (len(matched_skills) / len(job_skills) * 100) if job_skills else 0

        return {
            'similarity_score': similarity_score,
            'skills_found': skills,
            'matched_skills': matched_skills,
            'unmatched_job_skills': [s for s in job_skills if s not in skills],
            'years_experience': experience,
            'skill_match_percentage': skill_match_pct,
            'overall_score': (similarity_score * 0.5 + skill_match_pct * 0.5)
        }

