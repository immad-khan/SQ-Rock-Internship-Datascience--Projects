import matplotlib.pyplot as plt

def create_screening_visualization(results_sorted, job_name):
    """Create visualization for screening results"""

    fig = plt.figure(figsize=(16, 12))
    gs = fig.add_gridspec(3, 2, hspace=0.3, wspace=0.3)

    # 1. Overall Score Comparison
    ax1 = fig.add_subplot(gs[0, :])
    candidates = [r['Candidate'] for r in results_sorted]
    overall_scores = [r['Overall Score'] for r in results_sorted]
    colors = ['#2ecc71' if s >= 70 else '#f39c12' if s >= 50 else '#e74c3c' for s in overall_scores]

    bars = ax1.barh(candidates, overall_scores, color=colors)
    ax1.set_xlabel('Overall Match Score', fontsize=12, fontweight='bold')
    ax1.set_title(f'Resume Screening Results - {job_name}', fontsize=14, fontweight='bold')
    ax1.set_xlim(0, 100)
    ax1.grid(axis='x', alpha=0.3)

    for bar, score in zip(bars, overall_scores):
        ax1.text(score + 1, bar.get_y() + bar.get_height()/2,
                f'{score:.1f}%', va='center', fontweight='bold')

    # 2. Similarity Score vs Skill Match
    ax2 = fig.add_subplot(gs[1, 0])
    similarity = [r['Similarity Score'] for r in results_sorted]
    skill_match = [r['Skill Match %'] for r in results_sorted]

    x = range(len(candidates))
    width = 0.35

    ax2.bar([i - width/2 for i in x], similarity, width, label='Similarity Score', color='#3498db')
    ax2.bar([i + width/2 for i in x], skill_match, width, label='Skill Match %', color='#e74c3c')
    ax2.set_ylabel('Score (%)', fontweight='bold')
    ax2.set_title('Similarity vs Skill Match', fontweight='bold')
    ax2.set_xticks(x)
    ax2.set_xticklabels(candidates, rotation=45, ha='right')
    ax2.legend()
    ax2.grid(axis='y', alpha=0.3)

    # 3. Years of Experience
    ax3 = fig.add_subplot(gs[1, 1])
    years_exp = [r['Years Experience'] for r in results_sorted]
    colors_exp = ['#2ecc71' if y >= 4 else '#f39c12' if y >= 2 else '#e74c3c' for y in years_exp]

    ax3.bar(candidates, years_exp, color=colors_exp)
    ax3.set_ylabel('Years', fontweight='bold')
    ax3.set_title('Years of Experience', fontweight='bold')
    ax3.set_xticklabels(candidates, rotation=45, ha='right')
    ax3.grid(axis='y', alpha=0.3)

    # 4. Skills Match Details
    ax4 = fig.add_subplot(gs[2, :])
    ax4.axis('off')

    details_text = "📊 DETAILED SKILLS ANALYSIS:\n\n"
    for i, r in enumerate(results_sorted, 1):
        details_text += f"{i}. {r['Candidate']}\n"
        details_text += f"   ✅ Matched Skills: {', '.join(r['Matched Skills'][:5]) if r['Matched Skills'] else 'None'}\n"
        details_text += f"   ❌ Missing Skills: {', '.join(r['Unmatched Skills'][:5]) if r['Unmatched Skills'] else 'None'}\n\n"

    ax4.text(0.05, 0.95, details_text, transform=ax4.transAxes,
            fontsize=10, verticalalignment='top', family='monospace',
            bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.5))

    plt.savefig('screening_results.png', dpi=100, bbox_inches='tight')
    plt.close()

    return "screening_results.png"

