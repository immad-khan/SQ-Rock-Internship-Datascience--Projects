def create_churn_data():
    """Generate synthetic customer churn dataset"""
    np.random.seed(42)
    n_customers = 1000

    data = {
        'Age': np.random.randint(18, 75, n_customers),
        'Tenure_Months': np.random.randint(0, 72, n_customers),
        'Monthly_Charges': np.random.uniform(20, 150, n_customers),
        'Total_Charges': np.random.uniform(100, 8000, n_customers),
        'Internet_Service': np.random.choice(['Fiber', 'DSL', 'No'], n_customers),
        'Contract_Type': np.random.choice(['Month-to-Month', 'One-Year', 'Two-Year'], n_customers),
        'Payment_Method': np.random.choice(['Credit Card', 'Bank Transfer', 'Check', 'Electronic'], n_customers),
        'Monthly_Usage_GB': np.random.uniform(0, 500, n_customers),
        'Support_Tickets': np.random.randint(0, 10, n_customers),
        'Premium_Support': np.random.choice([0, 1], n_customers),
    }

    df = pd.DataFrame(data)

    # Create target variable with realistic relationships
    churn_probability = (
        (df['Tenure_Months'] < 12) * 0.3 +
        (df['Contract_Type'] == 'Month-to-Month') * 0.25 +
        (df['Monthly_Charges'] > 100) * 0.2 +
        (df['Support_Tickets'] > 5) * 0.15 +
        (df['Premium_Support'] == 0) * 0.1
    )

    df['Churn'] = (np.random.random(n_customers) < churn_probability).astype(int)

    return df

