def predict_churn(age, tenure, monthly_charges, total_charges, internet_service,
                  contract_type, payment_method, monthly_usage, support_tickets, premium_support):
    """
    Predict customer churn
    """
    try:
        # Validation
        if not (18 <= age <= 100):
            return "Error: Age must be between 18-100", None

        if tenure < 0 or tenure > 72:
            return "Error: Tenure must be 0-72 months", None

        if monthly_charges <= 0:
            return "Error: Monthly charges must be positive", None

        # Encode categorical variables
        internet_encoded = list(le_internet.classes_).index(internet_service)
        contract_encoded = list(le_contract.classes_).index(contract_type)
        payment_encoded = list(le_payment.classes_).index(payment_method)

        # Prepare input
        input_data = np.array([[
            age, tenure, monthly_charges, total_charges,
            internet_encoded, contract_encoded, payment_encoded,
            monthly_usage, support_tickets, premium_support
        ]])

        # Make prediction
        churn_pred = model.predict(input_data)[0]
        churn_prob = model.predict_proba(input_data)[0][1] * 100

        # Create visualization
        fig, axes = plt.subplots(1, 2, figsize=(14, 5))

        # Churn probability gauge
        color = '#e74c3c' if churn_prob > 50 else '#f39c12' if churn_prob > 30 else '#2ecc71'

        axes[0].barh(['Churn Risk'], [churn_prob], color=color, height=0.5)
        axes[0].barh(['Safe'], [100-churn_prob], left=[churn_prob], color='lightgray', height=0.5, alpha=0.3)
        axes[0].set_xlim(0, 100)
        axes[0].set_title('Churn Risk Assessment', fontweight='bold', fontsize=12)
        axes[0].text(churn_prob/2, 0, f'{churn_prob:.1f}%',
                    ha='center', va='center', fontsize=14, fontweight='bold', color='white')
        axes[0].set_xlabel('Risk Level (%)')

        # Customer profile
        profile_data = {
            'Metric': ['Age', 'Tenure', 'Monthly\nCharges', 'Usage\n(GB)', 'Support\nTickets'],
            'Value': [age, tenure, f'${monthly_charges:.0f}', f'{monthly_usage:.0f}', support_tickets]
        }

        axes[1].axis('off')
        table_data = [[f"{profile_data['Metric'][i]}: {profile_data['Value'][i]}"]
                     for i in range(len(profile_data['Metric']))]

        customer_info = f"""
        CUSTOMER PROFILE:
        • Age: {age} years
        • Tenure: {tenure} months
        • Monthly Charges: ${monthly_charges:.2f}
        • Total Charges: ${total_charges:.2f}
        • Internet Service: {internet_service}
        • Contract Type: {contract_type}
        • Monthly Usage: {monthly_usage:.0f} GB
        • Support Tickets: {support_tickets}
        • Premium Support: {"Yes" if premium_support else "No"}
        """

        axes[1].text(0.1, 0.5, customer_info, fontsize=11, family='monospace',
                    verticalalignment='center', bbox=dict(boxstyle='round',
                    facecolor='wheat', alpha=0.5))

        plt.tight_layout()
        plt.savefig('churn_prediction.png', dpi=100, bbox_inches='tight')
        plt.close()

        # Prepare report
        if churn_prob > 60:
            risk_category = "🔴 HIGH RISK"
            recommendation = """
            ⚠️ URGENT ACTION REQUIRED:
            • Offer special retention discount
            • Assign dedicated customer success manager
            • Provide premium support
            • Consider loyalty program
            • Schedule follow-up call immediately
            """
        elif churn_prob > 40:
            risk_category = "🟡 MEDIUM RISK"
            recommendation = """
            ⚠️ ACTION RECOMMENDED:
            • Monitor customer closely
            • Offer contract upgrade incentives
            • Ensure proactive customer support
            • Personalize service offerings
            • Check in quarterly
            """
        else:
            risk_category = "🟢 LOW RISK"
            recommendation = """
            ✅ STANDARD MANAGEMENT:
            • Maintain regular service quality
            • Periodic satisfaction surveys
            • Standard support response
            • Continue current engagement
            • Monitor for changes
            """

        report = f"""
        🎯 CHURN PREDICTION ANALYSIS
        {'='*50}

        🔮 PREDICTION: {risk_category}
        Churn Probability: {churn_prob:.2f}%

        {'='*50}
        📋 CUSTOMER DETAILS:
        • Age: {age} years
        • Tenure: {tenure} months
        • Monthly Charges: ${monthly_charges:.2f}
        • Internet Service: {internet_service}
        • Contract Type: {contract_type}
        • Support Tickets: {support_tickets}

        {'='*50}
        💡 RECOMMENDATIONS:
        {recommendation}

        ✅ Analysis complete!
        {'='*50}
        """

        return report, "churn_prediction.png"

    except Exception as e:
        return f"Error: {str(e)}", None

